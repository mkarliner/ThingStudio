#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# firmware/build.sh
#
# Builds Thingstudio's MicroPython image for one target: the runtime and every flow library frozen in. A target is
# a folder under firmware/targets/ (its facts in target.json, its board files in board/); this script names none of
# them. It needs ESP-IDF and the chip's toolchain, so it runs on a developer machine, not in the agent sandbox.
#
# Usage:
#   MICROPY_DIR=~/micropython firmware/build.sh <target>        # e.g. classic-esp32, esp32-c3, esp32-c5
#   python3 tools/firmware_targets.py list                      # the targets there are
#
# MICROPY_DIR is a MicroPython checkout at the target's pinned tag (target.json "micropython") with ports/esp32's
# submodules fetched, and IDF_PATH an ESP-IDF at the target's "espIdf" tag with its export script sourced. A
# checkout at another tag is refused: the pins are what makes a published image rebuildable.
#
# Output in firmware/out/<target>/:
#   thingstudio-<target>-<version>-<sha>.bin   merged image, written at the target's "address"
#   ...bin.sha256
#   _deps.json                                 the inventory source; frozen in as deps_frozen.py
#   main.py                                    written to /main.py (install.sh does it)
#
# A tree with uncommitted changes under device-runtime/ or firmware/ builds an image named ...-<sha>-dirty.bin,
# which record-tested.sh and publish.sh refuse: the commit in the name must be the code in the image.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
TARGET="${1:-}"
MICROPY_DIR="${MICROPY_DIR:-}"

die() { echo "build: $*" >&2; exit 1; }

[ -n "$TARGET" ] || die "usage: MICROPY_DIR=<checkout> $0 <target>  (targets: $(python3 "$REPO/tools/firmware_targets.py" list | tr '\n' ' '))"
ENV="$(python3 "$REPO/tools/firmware_targets.py" env "$TARGET")" || exit 1
eval "$ENV"

OUT="$HERE/out/$TARGET_ID"
STAGE="$OUT/stage"
TDIR="$HERE/targets/$TARGET_ID"

[ -n "$MICROPY_DIR" ] || die "set MICROPY_DIR to a MicroPython checkout at $TARGET_MPY_VERSION"
[ -f "$MICROPY_DIR/tools/manifestfile.py" ] || die "$MICROPY_DIR doesn't look like a MicroPython checkout"
[ -d "$MICROPY_DIR/ports/esp32" ] || die "$MICROPY_DIR has no ports/esp32"
ESPTOOL="$(command -v esptool.py || command -v esptool || true)"
[ -n "$ESPTOOL" ] || die "esptool not found on PATH (pip install esptool)"
command -v node >/dev/null || die "node not found on PATH (gen_deps_index.mjs compiles with the editor's mpy-cross)"
[ -n "${IDF_PATH:-}" ] || die "IDF_PATH is not set -- source the export script of ESP-IDF $TARGET_IDF_VERSION first"
[ -f "$IDF_PATH/tools/idf.py" ] || die "no idf.py under IDF_PATH=$IDF_PATH"

CHECKOUT="$(git -C "$MICROPY_DIR" describe --tags --exact-match 2>/dev/null || git -C "$MICROPY_DIR" describe --tags --always 2>/dev/null || echo unknown)"
[ "$CHECKOUT" = "$TARGET_MPY_VERSION" ] \
    || die "MicroPython checkout is $CHECKOUT; $TARGET_ID is pinned to $TARGET_MPY_VERSION (git -C $MICROPY_DIR checkout $TARGET_MPY_VERSION, then make -C ports/esp32 submodules)"
IDF_CHECKOUT="$(git -C "$IDF_PATH" describe --tags --exact-match 2>/dev/null || git -C "$IDF_PATH" describe --tags --always 2>/dev/null || echo unknown)"
[ "$IDF_CHECKOUT" = "$TARGET_IDF_VERSION" ] \
    || die "ESP-IDF at $IDF_PATH is $IDF_CHECKOUT; $TARGET_ID is pinned to $TARGET_IDF_VERSION"

echo "build: $TARGET_ID ($TARGET_LABEL) -- MicroPython $TARGET_MPY_VERSION, ESP-IDF $TARGET_IDF_VERSION, IDF_TARGET $TARGET_IDF_TARGET"

# 1. Stage exactly what runtime_manifest.py says a board gets (runtime core, listener, every vendored library and
#    font), under its on-board module names. The same set for every target.
python3 "$HERE/stage.py" "$STAGE"

# 2. The inventory the board reports, so Deploy skips what is already frozen.
node "$HERE/gen_deps_index.mjs" "$STAGE" "$OUT/_deps.json"

# 2b. Freeze that inventory into the image: deps.read_index() falls back to deps_frozen.INVENTORY, and a file
#     Deploy writes still wins. One source (gen_deps_index.mjs) for both, so the hashes cannot drift.
python3 - "$OUT/_deps.json" "$STAGE/deps_frozen.py" <<'PY'
import json, sys
data = json.load(open(sys.argv[1]))
with open(sys.argv[2], "w") as f:
    f.write("# Generated by firmware/build.sh -- the libraries this image freezes.\n")
    f.write("# deps.read_index() uses it when /lib/_deps.json is absent.\n")
    f.write("INVENTORY = %r\n" % (data,))
PY

# 2c. /main.py for the install script: the same boot script a stock install writes (runtime_manifest.BOOT_SCRIPT).
python3 - "$REPO/device-runtime/runtime_manifest.py" "$OUT/main.py" <<'PY'
import sys
sys.path.insert(0, sys.argv[1].rsplit("/", 1)[0])
import runtime_manifest
open(sys.argv[2], "wb").write(runtime_manifest.BOOT_SCRIPT)
PY

# 3. mpy-cross from this same tree, or the frozen bytecode version won't match the interpreter.
make -C "$MICROPY_DIR/mpy-cross" -j"$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)"

# 3b. Patches against the pinned port (patches/README.md). A failure to apply is fatal: a silently-unpatched tree
#     would build an image that drops bytes on a long serial line.
for p in "$HERE"/patches/*.patch; do
    [ -f "$p" ] || continue
    if git -C "$MICROPY_DIR" apply --check --reverse "$p" 2>/dev/null; then
        echo "build: $(basename "$p") already applied"
    elif git -C "$MICROPY_DIR" apply "$p"; then
        echo "build: applied $(basename "$p")"
    else
        die "$(basename "$p") does not apply to $MICROPY_DIR -- the MicroPython checkout has moved; refresh the patch"
    fi
done

# 3c. The board directory: the target's own files, plus three generated from target.json so each fact has one home.
BOARD_DIR="$MICROPY_DIR/ports/esp32/boards/$TARGET_BOARD"
rm -rf "${BOARD_DIR:?}"
cp -r "$TDIR/board" "$BOARD_DIR"
cp "$HERE/manifest.py" "$BOARD_DIR/manifest.py"
cat > "$BOARD_DIR/sdkconfig.partitions" <<EOF
# Generated by firmware/build.sh: the partition table is the target's board/partitions.csv.
CONFIG_PARTITION_TABLE_CUSTOM=y
CONFIG_PARTITION_TABLE_CUSTOM_FILENAME="boards/$TARGET_BOARD/partitions.csv"
EOF
{
    echo "# Generated by firmware/build.sh from firmware/targets/$TARGET_ID/target.json."
    echo "set(IDF_TARGET $TARGET_IDF_TARGET)"
    echo "set(SDKCONFIG_DEFAULTS"
    for fragment in $TARGET_PORT_SDKCONFIG; do echo "    $fragment"; done
    echo '    ${CMAKE_CURRENT_LIST_DIR}/sdkconfig.board'
    echo '    ${CMAKE_CURRENT_LIST_DIR}/sdkconfig.partitions'
    echo ")"
    # Set here, not as FROZEN_MANIFEST on the make line: a command-line variable propagates into the recursive
    # mpy-cross build, which then tries to freeze modules into mpy-cross itself ("assert mod_defs").
    echo 'set(MICROPY_FROZEN_MANIFEST ${CMAKE_CURRENT_LIST_DIR}/manifest.py)'
} > "$BOARD_DIR/mpconfigboard.cmake"

# No BUILD= on the make line: it would propagate into the recursive mpy-cross build and share its qstr tables
# ("MP_QSTR_asm_thumb undeclared"). The port's default build directory keeps the two apart.
rm -rf "$MICROPY_DIR/ports/esp32/build-$TARGET_BOARD"
THINGSTUDIO_FROZEN_STAGE="$STAGE" make -C "$MICROPY_DIR/ports/esp32" \
    BOARD="$TARGET_BOARD" \
    -j"$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)"

# 4. One merged image (bootloader + partition table + app) at the offsets ESP-IDF recorded in flash_args, starting
#    at the target's address. Writing one file can't get the offsets wrong.
BUILD_DIR="$MICROPY_DIR/ports/esp32/build-$TARGET_BOARD"
FIRST=""
while read -r offset _; do
    case "$offset" in 0x*) if [ -z "$FIRST" ] || [ $((offset)) -lt $((FIRST)) ]; then FIRST="$offset"; fi ;; esac
done < "$BUILD_DIR/flash_args"
[ -n "$FIRST" ] || die "cannot read the bootloader offset from $BUILD_DIR/flash_args"
[ $((FIRST)) -ge $((TARGET_ADDRESS)) ] \
    || die "flash_args starts at $FIRST, below the target's address $TARGET_ADDRESS -- fix target.json"

VERSION="$(python3 -c 'import sys; sys.path.insert(0, sys.argv[1]); import firmware_targets as t; print(t.runtime_version())' "$REPO/tools")"
SHA="$(git -C "$REPO" rev-parse --short=7 HEAD 2>/dev/null || echo unknown)"
if [ -n "$(git -C "$REPO" status --porcelain -- device-runtime firmware 2>/dev/null)" ]; then
    echo "build: WARNING uncommitted changes under device-runtime/ or firmware/ -- naming the image -dirty" >&2
    SHA="$SHA-dirty"
fi
IMG="$OUT/$TARGET_BUILD_ID-$VERSION-$SHA.bin"

( cd "$BUILD_DIR" && "$ESPTOOL" --chip "$TARGET_CHIP" merge_bin --target-offset "$TARGET_ADDRESS" -o "$IMG" @flash_args )
if command -v sha256sum >/dev/null; then ( cd "$OUT" && sha256sum "$(basename "$IMG")" > "$(basename "$IMG").sha256" )
else ( cd "$OUT" && shasum -a 256 "$(basename "$IMG")" > "$(basename "$IMG").sha256" ); fi

echo
echo "image:  $IMG"
echo "write:  at $TARGET_ADDRESS"
echo "size:   $(du -h "$IMG" | cut -f1)"
echo "install with: PORT=<port> $HERE/install.sh $TARGET_ID"
