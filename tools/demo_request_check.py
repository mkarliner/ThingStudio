#!/usr/bin/env python3
"""Browser check for the online editor demo: it works, and it sends nothing.

Serves a built demo (editor/dist-demo) on a local port with the headers from packaging/demo-server/Caddyfile,
opens it in headless Chromium (Playwright) and records every request the page and its workers make. Then it opens
every example from the Examples menu, presses Compile, and checks the Python preview; saves the flow, opens it
again, downloads the Python; and checks the narrow-screen message. It fails on any request outside the page's own
origin, any console error (a Content-Security-Policy violation is one), or any check that doesn't pass.

The JSON report (--report) is the evidence behind any "the demo sends nothing" line on the website: keep it. The
release workflow attaches it to the release beside the demo zip.

Usage:  python tools/demo_request_check.py [--static-dir editor/dist-demo] [--report demo-request-report.json]
                                           [--csp header|meta] [--allow-host HOST ...] [--chromium PATH]
  --csp meta    serve a copy with the policy as a <meta> tag and no headers, as the GitHub Pages standby does
  --allow-host  a host the page may also reach (only if a GoatCounter script is added to the page)
Needs:  a built demo (cd editor && npm run build:demo), and
        pip install -r docs/screenshots/requirements.txt && playwright install chromium
        On a minimal Linux with no fonts, point FONTCONFIG_FILE at a fonts.conf listing a TTF (tools/fonts/ works);
        see learnings/headless-browser-testing.md.
"""

from __future__ import annotations

import argparse
import functools
import json
import re
import shutil
import subprocess
import sys
import tempfile
import threading
import time
from collections import Counter
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlsplit

REPO = Path(__file__).resolve().parent.parent
CADDYFILE = REPO / "packaging" / "demo-server" / "Caddyfile"
ADD_META_CSP = REPO / "packaging" / "demo-server" / "add_meta_csp.py"
READY_TIMEOUT_MS = 30_000
COMPILE_TIMEOUT_MS = 30_000
PREVIEW_HEADER = "generated by the Thingstudio compiler"
RESULT_LINES = ("[compiled]", "[compile error]", "[mpy-cross error]")


def caddy_headers(caddyfile: Path = CADDYFILE) -> dict[str, str]:
    """The response headers the demo server sends: the `header { ... }` block of the Caddyfile."""
    text = caddyfile.read_text()
    block = re.search(r"^\s*header \{\n(.*?)^\s*\}", text, re.M | re.S)
    if not block:
        raise SystemExit(f"no header block in {caddyfile}")
    headers = dict(re.findall(r'^\s*([A-Z][A-Za-z-]+)\s+"([^"]*)"\s*$', block.group(1), re.M))
    headers.pop("Strict-Transport-Security", None)  # meaningless over the local http server
    if "Content-Security-Policy" not in headers:
        raise SystemExit(f"no Content-Security-Policy in {caddyfile}'s header block")
    return headers


class DemoHandler(SimpleHTTPRequestHandler):
    extra_headers: dict[str, str] = {}
    extensions_map = {**SimpleHTTPRequestHandler.extensions_map, ".wasm": "application/wasm", ".mjs": "text/javascript", ".js": "text/javascript"}

    def end_headers(self) -> None:
        for name, value in self.extra_headers.items():
            self.send_header(name, value)
        super().end_headers()

    def list_directory(self, path):  # no listing, as on the real server
        self.send_error(404)
        return None

    def log_message(self, *args) -> None:
        pass


def serve(directory: Path, headers: dict[str, str]) -> tuple[ThreadingHTTPServer, str]:
    handler = functools.partial(type("H", (DemoHandler,), {"extra_headers": headers}), directory=str(directory))
    server = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server, f"http://127.0.0.1:{server.server_address[1]}/"


class Check:
    def __init__(self) -> None:
        self.results: list[dict] = []

    def report(self, name: str, ok: bool, detail: str = "") -> bool:
        self.results.append({"check": name, "pass": ok, "detail": detail})
        print(f"{'PASS' if ok else 'FAIL'}  {name}{'  -- ' + detail if detail else ''}")
        return ok

    @property
    def passed(self) -> bool:
        return all(r["pass"] for r in self.results)


def console_lines(page) -> list[str]:
    """Every console line, shown or not: the console hides info-level lines at its default level."""
    return page.evaluate("Array.from(document.getElementById('console')?.children ?? []).map((r) => r.textContent ?? '')")


def count_lines(page, *needles: str) -> int:
    return sum(1 for line in console_lines(page) if any(n in line for n in needles))


def wait_for_more(page, needles: tuple[str, ...], before: int, timeout_ms: int) -> None:
    page.wait_for_function(
        "([needles, before]) => Array.from(document.getElementById('console')?.children ?? [])"
        ".filter((r) => needles.some((n) => (r.textContent ?? '').includes(n))).length > before",
        arg=[list(needles), before],
        timeout=timeout_ms,
    )


def last_line_with(page, needles: tuple[str, ...]) -> str:
    lines = [line for line in console_lines(page) if any(n in line for n in needles)]
    return lines[-1].strip() if lines else ""


def open_menu(page, list_id: str) -> None:
    page.locator(f"#{list_id}").locator("xpath=..").locator(".menu-button").click()


def run(page, check: Check, tmp: Path) -> list[dict]:
    # Predicates are functions, not expression strings: Playwright evaluates a string with eval(), which the
    # demo's Content-Security-Policy rightly refuses.
    page.wait_for_function("() => document.getElementById('console')?.textContent.includes('[flow loaded')", timeout=READY_TIMEOUT_MS)
    page.wait_for_function("() => document.getElementById('console')?.textContent.includes('[mpy-cross WASM ready]')", timeout=READY_TIMEOUT_MS)
    check.report("opens with an example loaded", True, last_line_with(page, ("[flow loaded",)))

    visible = {sel: page.locator(sel).is_visible() for sel in ("#demo-banner", "#btnCompile", "#btnConnect", "#btnDeploy", "#backendPortSelect", "#btnSaveFlow", "#cmdInput")}
    check.report("banner and Compile shown", visible["#demo-banner"] and visible["#btnCompile"])
    hidden = [s for s in ("#btnConnect", "#btnDeploy", "#backendPortSelect", "#btnSaveFlow", "#cmdInput") if visible[s]]
    check.report("board controls hidden", not hidden, f"still visible: {', '.join(hidden)}" if hidden else "")
    tools_visible = page.get_by_role("button", name="Tools ▾").is_visible()
    check.report("Tools menu hidden", not tools_visible)

    examples: list[dict] = []
    items = page.locator("#examplesMenuList > button")
    for i in range(items.count()):
        label = (items.nth(i).text_content() or "").strip()
        loaded = count_lines(page, "[flow loaded")
        open_menu(page, "examplesMenuList")
        items.nth(i).click()
        wait_for_more(page, ("[flow loaded",), loaded, READY_TIMEOUT_MS)
        results = count_lines(page, *RESULT_LINES)
        page.click("#btnCompile")
        wait_for_more(page, RESULT_LINES, results, COMPILE_TIMEOUT_MS)
        line = last_line_with(page, RESULT_LINES)
        preview = page.evaluate("document.getElementById('source-preview')?.textContent ?? ''")
        ok = "[compiled]" in line and PREVIEW_HEADER in preview and "COMPILE ERROR" not in preview
        examples.append({"example": label, "pass": ok, "result": line, "pythonLines": preview.count("\n") + 1})
        check.report(f"example compiles: {label}", ok, line)

    preview_open = page.evaluate("document.getElementById('previewPanel')?.open === true")
    check.report("Compile opens the Python preview", preview_open)

    # Download .py: the compiled source, as a file.
    with page.expect_download(timeout=READY_TIMEOUT_MS) as dl:
        page.click("#btnDownloadPython")
    py = tmp / dl.value.suggested_filename
    dl.value.save_as(py)
    check.report("Download .py", py.suffix == ".py" and PREVIEW_HEADER in py.read_text(), py.name)

    # Save As downloads the flow; Open reads it back through a plain file input.
    open_menu(page, "fileMenuList")
    with page.expect_download(timeout=READY_TIMEOUT_MS) as dl:
        page.click("#btnSaveFlowAs")
    saved = tmp / dl.value.suggested_filename
    dl.value.save_as(saved)
    try:
        nodes = len(json.loads(saved.read_text())["nodes"])
    except (ValueError, KeyError):
        nodes = -1
    check.report("Save As downloads the flow", nodes > 0, f"{saved.name}, {nodes} nodes")

    loaded = count_lines(page, "[flow loaded")
    open_menu(page, "fileMenuList")
    with page.expect_file_chooser(timeout=READY_TIMEOUT_MS) as chooser:
        page.click("#btnOpenFlow")
    chooser.value.set_files(str(saved))
    wait_for_more(page, ("[flow loaded",), loaded, READY_TIMEOUT_MS)
    check.report("Open reads a flow file", True, last_line_with(page, ("[flow loaded",)))
    return examples


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--static-dir", type=Path, default=REPO / "editor" / "dist-demo")
    parser.add_argument("--report", type=Path, default=Path("demo-request-report.json"))
    parser.add_argument("--csp", choices=("header", "meta"), default="header")
    parser.add_argument("--allow-host", action="append", default=[])
    parser.add_argument("--chromium", default=None, help="Chromium executable (default: Playwright's own)")
    args = parser.parse_args()
    if not (args.static_dir / "index.html").is_file():
        print(f"no built demo at {args.static_dir} -- run: cd editor && npm run build:demo", file=sys.stderr)
        return 2
    from playwright.sync_api import sync_playwright

    tmp = Path(tempfile.mkdtemp(prefix="thingstudio-demo-check-"))
    headers = caddy_headers()
    policy = headers["Content-Security-Policy"]
    site = args.static_dir
    if args.csp == "meta":
        site = tmp / "site"
        shutil.copytree(args.static_dir, site)
        subprocess.run([sys.executable, str(ADD_META_CSP), str(site)], check=True)
        headers = {}
    server, base_url = serve(site, headers)
    origin = urlsplit(base_url)
    allowed = {origin.netloc, *args.allow_host}

    check = Check()
    requests: list[str] = []
    errors: list[str] = []
    examples: list[dict] = []
    version = ""
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(executable_path=args.chromium) if args.chromium else pw.chromium.launch()
            ctx = browser.new_context(viewport={"width": 1440, "height": 900}, accept_downloads=True)
            ctx.on("request", lambda r: requests.append(r.url))
            ctx.add_init_script(
                "document.addEventListener('securitypolicyviolation', e =>"
                " console.error(`CSP violation: ${e.violatedDirective} blocked ${e.blockedURI || '(inline)'}`));"
            )

            def watch(page) -> None:
                page.on("console", lambda m: errors.append(f"console: {m.text}") if m.type == "error" else None)
                page.on("pageerror", lambda e: errors.append(f"page error: {e}"))
                page.on("worker", lambda w: w.on("console", lambda m: errors.append(f"worker console: {m.text}") if m.type == "error" else None))

            page = ctx.new_page()
            watch(page)
            page.goto(base_url)
            examples = run(page, check, tmp)
            version = (page.text_content("#demo-version") or "").strip()
            page.close()

            narrow = ctx.new_page()
            watch(narrow)
            narrow.set_viewport_size({"width": 700, "height": 900})
            narrow.goto(base_url)
            narrow.wait_for_timeout(500)
            check.report(
                "narrow screen shows the desktop message",
                narrow.locator("#narrow-screen").is_visible() and not narrow.locator("#app").is_visible(),
            )
            narrow.close()
            browser.close()
    finally:
        server.shutdown()

    def off_origin(url: str) -> bool:
        parts = urlsplit(url)
        return parts.scheme not in ("data", "blob") and parts.netloc not in allowed

    leaving = sorted({u for u in requests if off_origin(u)})
    check.report("no request leaves the page's origin", not leaving, ", ".join(leaving[:5]))
    check.report("no console errors", not errors, "; ".join(errors[:5]))

    counts = Counter(urlsplit(u)._replace(netloc="<origin>" if urlsplit(u).netloc == origin.netloc else urlsplit(u).netloc).geturl() for u in requests)
    report = {
        "what": "Thingstudio online demo: requests made while opening and compiling every example (tools/demo_request_check.py)",
        "checkedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "editorVersion": version,
        "browser": "Chromium (Playwright), headless",
        "cspMode": args.csp,
        "contentSecurityPolicy": policy,
        "allowedHosts": sorted(args.allow_host),
        "pass": check.passed,
        "checks": check.results,
        "examples": examples,
        "requestsLeavingOrigin": leaving,
        "consoleErrors": errors,
        "requests": [{"url": u, "count": n} for u, n in sorted(counts.items())],
    }
    args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(f"{'PASS' if check.passed else 'FAIL'}: {len(requests)} requests, {len(leaving)} off-origin; report in {args.report}")
    shutil.rmtree(tmp, ignore_errors=True)
    return 0 if check.passed else 1


if __name__ == "__main__":
    sys.exit(main())
