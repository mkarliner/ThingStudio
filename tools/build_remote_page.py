# tools/build_remote_page.py
#
# Builds the remote display's page asset module (spike, 2026-11-06): the hand-authored page at
# device-runtime/src/vendor/thingstudio_remote/page/remote.html goes into
# device-runtime/src/vendor/thingstudio_remote/page_data.py as its already-gzipped bytes
# (page_data.PAGE_GZ) plus a content hash (page_data.PAGE_VERSION, the ETag the board serves with it).
# The board never decompresses anything: it serves the gzip bytes exactly as stored and the page
# says Content-Encoding: gzip (working item 12).
#
# Keeps the human-readable source (the file a person audits) and its board-side form both real: rerun this
# whenever remote.html changes; the tests refuse PAGE_GZ that does not match a fresh gzip of the source.
# Deploys carry page_data.py through the ordinary dependency mechanism (mpy-cross embeds the bytes
# unchanged), so no deps.py schema change is needed for a non-.py asset.

import argparse
import gzip
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "device-runtime/src/vendor/thingstudio_remote/page/remote.html"
TARGET = ROOT / "device-runtime/src/vendor/thingstudio_remote/ts_remote/page_data.py"


def build(source: pathlib.Path, target: pathlib.Path) -> int:
    raw = source.read_bytes()
    packed = gzip.compress(raw, 9, mtime=0)  # deterministic: no embedded timestamp
    version = hashlib.sha256(raw).hexdigest()[:12]
    text = (
        '# SPDX-License-Identifier: Apache-2.0\n'
        '# device-runtime/src/vendor/thingstudio_remote/page_data.py\n'
        '# Generated by tools/build_remote_page.py from page/remote.html -- do not edit; edit the source\n'
        '# page and rerun the tool (the tests check the two agree). The board serves PAGE_GZ as-is with\n'
        '# Content-Encoding: gzip; PAGE_VERSION is the source content hash and the served ETag.\n\n'
        f'PAGE_VERSION = "{version}"\n'
        f'PAGE_GZ = {packed!r}\n'
    )
    target.write_text(text)
    print(f"built {target.relative_to(ROOT)}: {len(raw)} bytes raw -> {len(packed)} gzipped, v{version}")
    return len(packed)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="build in memory and fail if page_data.py is not current")
    args = parser.parse_args()
    raw = SOURCE.read_bytes()
    packed = gzip.compress(raw, 9, mtime=0)  # deterministic: no embedded timestamp
    version = hashlib.sha256(raw).hexdigest()[:12]
    if args.check:
        current = TARGET.read_text() if TARGET.exists() else ""
        if f'PAGE_VERSION = "{version}"' not in current or repr(packed) not in current:
            print(f"stale: {TARGET} does not match {SOURCE} -- run tools/build_remote_page.py")
            return 1
        print(f"current: {len(raw)} bytes raw -> {len(packed)} gzipped, v{version}")
        return 0
    build(SOURCE, TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
