# tools/protocol_states.py
#
# interfaces/protocol/states.json is the ground truth for the wire protocol's state machines (SPEC.md §7). This
# checks it and generates everything that follows from it:
#
#   interfaces/protocol/STATES.md              for people: each machine's states, diagram and transition table
#   device-runtime/src/protocol_states.py      the board's machines, as data the board's interpreter runs
#   editor/src/protocol/states.generated.ts    the editor's machines, as data the editor's interpreter runs
#
#   python3 tools/protocol_states.py           regenerate the three
#   python3 tools/protocol_states.py --check   exit 1 if states.json is inconsistent or any output is stale
#
# Plain standard-library Python, reads and writes files only.

import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
PROTO = os.path.join(ROOT, "interfaces", "protocol")
SOURCE = os.path.join(PROTO, "states.json")
OUT_MD = os.path.join(PROTO, "STATES.md")
OUT_PY = os.path.join(ROOT, "device-runtime", "src", "protocol_states.py")
OUT_TS = os.path.join(ROOT, "editor", "src", "protocol", "states.generated.ts")
GENERATED = "Generated by tools/protocol_states.py from interfaces/protocol/states.json. Do not edit by hand."


def load():
    with open(SOURCE, encoding="utf-8") as f:
        table = json.load(f)
    with open(os.path.join(PROTO, "messages.json"), encoding="utf-8") as f:
        message_names = {m["name"] for m in json.load(f)["messages"]}
    return table, message_names


def from_states(machine, t):
    f = t["from"]
    if f == "*":
        return list(machine["states"])
    return [f] if isinstance(f, str) else list(f)


def validate(table, message_names):
    problems = []
    for name, m in table["machines"].items():
        where = "machine %s" % name
        states, events = m["states"], m["events"]
        guards, actions = m.get("guards", {}), m.get("actions", {})
        if m.get("side") not in ("board", "editor"):
            problems.append("%s: side must be board or editor" % where)
        if m["initial"] not in states:
            problems.append("%s: initial state %r is not a state" % (where, m["initial"]))
        used_actions, used_guards = set(), set()
        for i, t in enumerate(m["transitions"]):
            tw = "%s transition %d (%s)" % (where, i + 1, t.get("on"))
            for s in from_states(m, t):
                if s not in states:
                    problems.append("%s: from-state %r is not a state" % (tw, s))
            if t["on"] not in events:
                problems.append("%s: event %r is not listed in events" % (tw, t["on"]))
            for key, pool, used in (("if", guards, used_guards), ("do", actions, used_actions)):
                if key in t:
                    used.add(t[key])
                    if t[key] not in pool:
                        problems.append("%s: %s %r is not described" % (tw, "guard" if key == "if" else "action", t[key]))
            for to in [t.get("to")] + ([t["onError"]["to"]] if "onError" in t else []):
                if to != "same" and to not in states:
                    problems.append("%s: to-state %r is not a state" % (tw, to))
            for r in t.get("replies", []):
                if r not in message_names:
                    problems.append("%s: reply %r is not a message in messages.json" % (tw, r))
            if "onError" in t and "do" not in t:
                problems.append("%s: onError without an action that can fail" % (tw,))
        for ev, rule in m.get("illegal", {}).items():
            if ev != "*" and ev not in events:
                problems.append("%s: illegal rule for unknown event %r" % (where, ev))
            if "do" in rule:
                used_actions.add(rule["do"])
                if rule["do"] not in actions:
                    problems.append("%s: illegal rule's action %r is not described" % (where, rule["do"]))
            if rule.get("to", "same") != "same" and rule["to"] not in states:
                problems.append("%s: illegal rule's to-state %r is not a state" % (where, rule["to"]))
        for a in sorted(set(actions) - used_actions):
            problems.append("%s: action %r is described but never used" % (where, a))
        for g in sorted(set(guards) - used_guards):
            problems.append("%s: guard %r is described but never used" % (where, g))
        for inst, mapping in m.get("instances", {}).items():
            for key in ("piece", "ack", "commit", "commitError"):
                if mapping.get(key) not in message_names:
                    problems.append("%s: instance %s's %s %r is not a message" % (where, inst, key, mapping.get(key)))
        if name == "board.listener":
            msg_events = {e for e in events if e in message_names}
            if msg_events != message_names:
                problems.append("%s: every message must be an event (missing: %s)" % (where, ", ".join(sorted(message_names - msg_events))))
    return problems


# --- STATES.md -------------------------------------------------------------------------------------------

def _reply_text(t):
    if "replies" in t:
        return ", ".join(t["replies"]) or "nothing"
    if "reply" in t:
        (kind, fields), = t["reply"].items()
        return "%s %s" % (kind, ", ".join("%s %s" % (k, json.dumps(v) if not isinstance(v, str) else v) for k, v in fields.items()))
    return ""


def _label(t):
    s = t["on"]
    if "if" in t:
        s += " [%s]" % t["if"]
    if "do" in t:
        s += " / %s" % t["do"]
    return s


def _diagram(name, m):
    lines = ["```mermaid", "stateDiagram-v2", "    direction TB", "    [*] --> %s" % m["initial"]]
    loops = {s: [] for s in m["states"]}
    edges = {}  # (from, to) -> labels, so one arrow carries every transition between the same two states

    def edge(a, b, label):
        if a == b:
            loops[a].append(label)
        else:
            edges.setdefault((a, b), []).append(label)

    for t in m["transitions"]:
        for s in from_states(m, t):
            edge(s, s if t["to"] == "same" else t["to"], _label(t))
            if "onError" in t:
                edge(s, s if t["onError"]["to"] == "same" else t["onError"]["to"], "%s fails" % t["do"])
    for ev, rule in m.get("illegal", {}).items():
        if rule.get("to", "same") != "same":
            for s in m["states"]:
                if s != rule["to"]:
                    edge(s, rule["to"], "illegal %s" % ev)
    for (a, b), labels in edges.items():
        lines.append("    %s --> %s : %s" % (a, b, "<br/>".join(labels)))
    for s, labels in loops.items():
        if labels:
            lines.append("    note right of %s" % s)
            lines.append("        stays on:")
            for lab in labels:
                lines.append("        %s" % lab.replace("[", "(").replace("]", ")"))
            lines.append("    end note")
    lines.append("```")
    return lines


def render_md(table):
    out = ["<!-- %s -->" % GENERATED, "", "# Wire protocol — state machines", ""]
    out += [
        "The protocol's state machines, generated from `states.json`, which is the ground truth (SPEC §7). Each",
        "side runs its machines straight from that table. To change a machine, edit `states.json`, run",
        "`python3 tools/protocol_states.py`, and update both implementations of any new guard or action.",
        "",
        "How to read a table: for an event, the **first** row whose *from* includes the current state and whose",
        "*guard* holds is taken. **Any (state, event) with no row is illegal**: the side running the machine",
        "raises an alert (SPEC §7.6) and then does what the machine's *illegal* rule says.",
        "",
    ]
    for name, m in table["machines"].items():
        out += ["## `%s` (%s)" % (name, m["side"]), "", m["about"], ""]
        if "instances" in m:
            out += ["Runs as:", ""]
            for inst, mp in m["instances"].items():
                out.append("- **%s**: piece = `%s`, its answer = `%s`, commit = `%s`, a refused commit = `%s`." % (
                    inst, mp["piece"], mp["ack"], mp["commit"], mp["commitError"]))
            out.append("")
        out += ["| State | Meaning |", "|---|---|"]
        out += ["| **%s**%s | %s |" % (s, " (initial)" if s == m["initial"] else "", d) for s, d in m["states"].items()]
        out.append("")
        if len(m["states"]) > 1:
            out += _diagram(name, m) + [""]
        out += ["| # | From | Event | Guard | Action | To | Reply |", "|---|---|---|---|---|---|---|"]
        for i, t in enumerate(m["transitions"]):
            frm = "any" if t["from"] == "*" else ", ".join(from_states(m, t))
            out.append("| %d | %s | `%s` | %s | %s | %s | %s |" % (
                i + 1, frm, t["on"], t.get("if", ""), t.get("do", ""), t["to"], _reply_text(t)))
            if "onError" in t:
                out.append("| | | | | *%s fails* | %s | %s |" % (t["do"], t["onError"]["to"], _reply_text(t["onError"])))
        out.append("")
        out += ["**Illegal** (no row matches): alert, then"]
        for ev, rule in m["illegal"].items():
            what = []
            if "do" in rule:
                what.append(rule["do"])
            what.append("state %s" % rule.get("to", "same"))
            if "reply" in rule:
                what.append("reply %s" % _reply_text(rule))
            out.append("- %s: %s." % ("any event" if ev == "*" else "`%s`" % ev, ", ".join(what)))
        out.append("")
        for title, key in (("Events", "events"), ("Guards", "guards"), ("Actions", "actions")):
            if m.get(key):
                out += ["**%s**" % title, ""]
                out += ["- `%s`: %s" % (k, v) for k, v in m[key].items()]
                out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


# --- code ------------------------------------------------------------------------------------------------

def _machine_data(m):
    """The parts an interpreter needs: no prose."""
    data = {"initial": m["initial"], "states": list(m["states"]), "transitions": [], "illegal": m["illegal"]}
    for t in m["transitions"]:
        row = {"from": from_states(m, t), "on": t["on"], "to": t["to"]}
        for k in ("if", "do", "replies", "reply", "onError"):
            if k in t:
                row[k] = t[k]
        data["transitions"].append(row)
    if "instances" in m:
        data["instances"] = m["instances"]
    return data


def _py(value):
    """A Python literal, with lists as tuples: on MicroPython a tuple is smaller than a list or a dict."""
    if isinstance(value, dict):
        return "{" + ", ".join("%r: %s" % (k, _py(v)) for k, v in sorted(value.items())) + "}"
    if isinstance(value, list):
        return "(" + "".join(_py(v) + ", " for v in value) + ")"
    return repr(value)


def render_py(table):
    """Each machine as (initial, transitions, illegal, instances). A transition is a tuple:
    (from_states, event, guard, action, to, replies, reply, on_error) -- None where absent."""
    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        "# " + GENERATED,
        "# The board's state machines (interfaces/protocol/STATES.md), run by machine.py. A machine is",
        "# (initial, transitions, illegal, instances); a transition is",
        "# (from_states, event, guard, action, to, replies, reply, on_error), None where absent.",
        "",
        "MACHINES = {",
    ]
    for name, m in table["machines"].items():
        if m["side"] != "board":
            continue
        lines.append("    %r: (" % name)
        lines.append("        %r," % m["initial"])
        lines.append("        (")
        for t in m["transitions"]:
            row = (from_states(m, t), t["on"], t.get("if"), t.get("do"), t["to"], t.get("replies"), t.get("reply"), t.get("onError"))
            lines.append("            %s," % _py(list(row)))
        lines.append("        ),")
        lines.append("        %s," % _py(m["illegal"]))
        lines.append("        %s," % _py(m.get("instances")))
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_ts(table):
    machines = {n: _machine_data(m) for n, m in table["machines"].items() if m["side"] == "editor"}
    return (
        "// SPDX-License-Identifier: Apache-2.0\n// %s\n"
        "// The editor's state machines (interfaces/protocol/STATES.md), run by machine.ts.\n\n"
        "export const MACHINES = %s as const;\n" % (GENERATED, json.dumps(machines, indent=2, sort_keys=True))
    )


def main():
    table, message_names = load()
    problems = validate(table, message_names)
    outputs = {OUT_MD: render_md(table), OUT_PY: render_py(table), OUT_TS: render_ts(table)}
    if "--check" in sys.argv[1:]:
        for path, text in outputs.items():
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if current != text:
                problems.append("%s is out of date: run python3 tools/protocol_states.py" % os.path.relpath(path, ROOT))
        for p in problems:
            print("protocol states: " + p)
        sys.exit(1 if problems else 0)
    if problems:
        for p in problems:
            print("protocol states: " + p)
        sys.exit(1)
    for path, text in outputs.items():
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
