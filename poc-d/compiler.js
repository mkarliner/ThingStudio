// Thingstudio POC-D — graph -> MicroPython compiler.
//
// Deliberately NOT a general-purpose compiler (design doc §15.5 out-of-scope:
// "the real v1 node set beyond these 3 types... the real msg envelope/type
// system"). This only knows how to compile exactly one shape:
//
//   inject --(msg)--> function --(msg)--> gpio_out
//
// and rejects anything else with a clear error rather than guessing. The real
// §6 compiler (graph JSON -> Python -> mpy-cross) is a v1-scope piece of work;
// this hardcodes the 3-node case just to prove the pipeline (canvas -> real
// MicroPython -> real .mpy bytecode -> real device) holds together end to end.
//
// Simplification called out in §15.5: "manual" repeat fires exactly once, at
// deploy time (there's no live "fire" round-trip in this spike's protocol —
// see harness.py). "1s"/"5s"/"30s" compile to a real loop with asyncio.sleep_ms.

(function () {
  "use strict";

  var REPEAT_MS = { manual: 0, "1s": 1000, "5s": 5000, "30s": 30000 };

  function CompileError(msg) {
    this.name = "CompileError";
    this.message = msg;
  }
  CompileError.prototype = Object.create(Error.prototype);

  // Python string-literal encoding good enough for short test values (not
  // adversarial input — this is a POC, not a hardened compiler).
  function pyStringLiteral(s) {
    return JSON.stringify(String(s)); // double-quoted + escaping matches Python's for basic ASCII
  }

  function pyPayloadLiteral(payloadType, rawValue) {
    switch (payloadType) {
      case "bool":
        return rawValue === "true" || rawValue === true ? "True" : "False";
      case "number": {
        var n = Number(rawValue);
        if (Number.isNaN(n)) throw new CompileError('inject payload value "' + rawValue + '" is not a valid number');
        return String(n);
      }
      default:
        return pyStringLiteral(rawValue);
    }
  }

  function indent(code, spaces) {
    var pad = " ".repeat(spaces);
    return code
      .split("\n")
      .map((line) => (line.length ? pad + line : line))
      .join("\n");
  }

  // graphData: output of LGraph.prototype.serialize() — { nodes: [...], links: [...] }
  function compile(graphData) {
    var nodesByType = { "thingstudio/inject": [], "thingstudio/function": [], "thingstudio/gpio_out": [] };
    (graphData.nodes || []).forEach((n) => {
      if (nodesByType[n.type]) nodesByType[n.type].push(n);
    });

    if (nodesByType["thingstudio/inject"].length !== 1)
      throw new CompileError(
        "expected exactly 1 inject node, found " + nodesByType["thingstudio/inject"].length
      );
    if (nodesByType["thingstudio/function"].length !== 1)
      throw new CompileError(
        "expected exactly 1 function node, found " + nodesByType["thingstudio/function"].length
      );
    if (nodesByType["thingstudio/gpio_out"].length !== 1)
      throw new CompileError(
        "expected exactly 1 gpio_out node, found " + nodesByType["thingstudio/gpio_out"].length
      );

    var inject = nodesByType["thingstudio/inject"][0];
    var fn = nodesByType["thingstudio/function"][0];
    var gpio = nodesByType["thingstudio/gpio_out"][0];

    // links: [link_id, origin_id, origin_slot, target_id, target_slot, type]
    var links = graphData.links || [];
    function isLinked(fromId, toId) {
      return links.some((l) => l[1] === fromId && l[3] === toId);
    }

    if (!isLinked(inject.id, fn.id))
      throw new CompileError("inject is not wired to function — expected inject → function → gpio_out");
    if (!isLinked(fn.id, gpio.id))
      throw new CompileError("function is not wired to gpio_out — expected inject → function → gpio_out");

    var payloadType = inject.properties.payloadType || "bool";
    var payloadLiteral = pyPayloadLiteral(payloadType, inject.properties.payloadValue);
    var repeat = inject.properties.repeat || "manual";
    var repeatMs = REPEAT_MS[repeat];
    if (repeatMs === undefined) throw new CompileError('unknown inject repeat value "' + repeat + '"');

    var pin = Math.round(Number(gpio.properties.pin));
    if (!Number.isFinite(pin) || pin < 0 || pin > 39)
      throw new CompileError("gpio_out pin " + gpio.properties.pin + " is out of range (0-39)");

    var userCode = (fn.properties.code || "").replace(/\r\n/g, "\n");
    if (!userCode.trim()) throw new CompileError("function node's code is empty");

    var src =
      "# --- generated by Thingstudio POC-D compiler (" + new Date().toISOString() + ") ---\n" +
      "# graph: inject -> function -> gpio_out. See design doc §15.5 for exactly what this does\n" +
      "# and doesn't do; this is NOT the real §6 compiler.\n" +
      "import harness_api\n" +
      "asyncio = harness_api.asyncio\n" +
      "import machine\n" +
      "\n" +
      "_pin = machine.Pin(" + pin + ", machine.Pin.OUT)\n" +
      "\n" +
      "def _node_function(msg):\n" +
      indent(userCode, 4) +
      "\n" +
      "\n" +
      "def _node_gpio_out(msg):\n" +
      "    _pin.value(1 if msg.get('payload') else 0)\n" +
      "\n" +
      "async def _flow_main():\n" +
      "    while True:\n" +
      "        msg = {'payload': " + payloadLiteral + ", 'topic': ''}\n" +
      "        result = _node_function(msg)\n" +
      "        if result is not None:\n" +
      "            _node_gpio_out(result)\n" +
      "        if " + repeatMs + " <= 0:\n" +
      "            break\n" +
      "        await asyncio.sleep_ms(" + repeatMs + ")\n" +
      "\n" +
      "harness_api.spawn(_flow_main())\n";

    return { source: src, meta: { payloadType, repeat, repeatMs, pin } };
  }

  window.ThingstudioCompiler = { compile, CompileError };
})();
