// The comment node (node-library/comment.ts, 2026-11-18): canvas-only, so the compiler leaves it out entirely.
import { describe, expect, it } from "vitest";
import { compile } from "../src/compiler/compile.js";
import type { GraphData } from "../src/compiler/graph.js";
import { buildRegistry } from "../src/node-library/registry.js";

const registry = buildRegistry();

const blink: GraphData = {
  nodes: [
    { id: "t", type: "thingstudio/timer", properties: { intervalMs: 500 } },
    { id: "g", type: "thingstudio/gpio_out", properties: { pin: 4 } },
  ],
  links: [[1, "t", 0, "g", 0, "any"]],
};
const comment = { id: "c", type: "thingstudio/comment", properties: { text: "Set pin to your board's LED.", width: 32, lines: 8 } };

describe("comment node", () => {
  it("is registered as canvas-only, with no ports and no code", () => {
    const def = registry.get("thingstudio/comment")!;
    expect(def.canvasOnly).toBe(true);
    expect(def.ports).toBeUndefined();
    expect(def.codegenSource ?? def.codegenEventSource ?? def.codegenTransform ?? def.codegenSink).toBeUndefined();
  });

  it("changes nothing in the compiled flow", () => {
    const body = (src: string): string => src.replace(/^# --- generated by .*\n/, ""); // the header carries a timestamp
    const without = body(compile(blink, registry).source);
    const withComment = body(compile({ ...blink, nodes: [comment, ...blink.nodes] }, registry).source);
    expect(withComment).toBe(without);
    expect(withComment).not.toContain("node:c");
  });

  it("refuses a flow file that wires one", () => {
    const wired: GraphData = { nodes: [...blink.nodes, comment], links: [...blink.links, [2, "t", 0, "c", 0, "any"]] };
    expect(() => compile(wired, registry)).toThrow(/canvas-only and takes no wires/);
  });

  it("alone is still a flow with no source", () => {
    expect(() => compile({ nodes: [comment], links: [] }, registry)).toThrow(/no source node/);
  });
});
